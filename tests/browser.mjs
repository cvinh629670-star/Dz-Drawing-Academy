import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {readFile} from 'node:fs/promises';
import {pack} from '../js/zip.js';
const [runner, executablePath, url='http://127.0.0.1:8765/']=process.argv.slice(2);
const {chromium}=await import(pathToFileURL(runner));
const browser=await chromium.launch({executablePath});
try {
  const context=await browser.newContext({viewport:{width:1440,height:1000},acceptDownloads:true});
  const page=await context.newPage();
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  page.on('dialog',async d=>d.accept(d.type()==='prompt'?'Nghiên cứu nét':undefined));
  const open=async(route,title)=>{
    await page.evaluate(route=>location.hash=route,route);
    await page.locator('main h1').filter({hasText:title}).waitFor();
  };
  const waitText=(selector,text)=>page.locator(selector).filter({hasText:text}).waitFor();
  await page.goto(url);
  await waitText('main h1','Chào Họa sĩ');
  await page.evaluate(()=>navigator.serviceWorker.ready);
  await page.waitForFunction(()=>Boolean(navigator.serviceWorker.controller));
  if(process.env.DZ_SCREENSHOT)await page.screenshot({path:process.env.DZ_SCREENSHOT});
  await open('lesson/line','Nét thẳng tự tin');
  await page.locator('#theory').click();
  await page.locator('#theory:disabled').waitFor();
  await page.locator('#warm').click();
  await page.locator('#warm:disabled').waitFor();
  await open('practice/line','Bàn vẽ');
  const canvas=page.locator('canvas');
  const snapshot=()=>canvas.evaluate(c=>c.toDataURL());
  await page.waitForTimeout(200);
  const before=await snapshot();
  const b=await canvas.boundingBox();
  await page.mouse.move(b.x+b.width*.35,b.y+b.height*.4);
  await page.mouse.down();
  await page.mouse.move(b.x+b.width*.63,b.y+b.height*.62,{steps:12});
  await page.mouse.up();
  const after=await snapshot();
  assert.notEqual(before,after);
  await page.locator('#undo').click();
  assert.equal(await snapshot(),before);
  await page.locator('#redo').click();
  assert.equal(await snapshot(),after);
  await waitText('#draft-status','đã lưu');
  await page.reload();
  await waitText('#draft-status','đã lưu');
  await page.waitForFunction(expected=>document.querySelector('canvas').toDataURL()===expected,after);
  await page.locator('[data-t=start]').click();
  await page.waitForTimeout(1150);
  await page.locator('[data-t=start]').click();
  const paused=await page.locator('output.timer').textContent();
  await page.waitForTimeout(1100);
  assert.equal(await page.locator('output.timer').textContent(),paused);
  await page.locator('[data-t=stop]').click();
  await page.locator('#save-art').click();
  await waitText('#notice','Đã lưu vào Portfolio');
  await open('lesson/line','Nét thẳng tự tin');
  await page.locator('#complete input[type=checkbox]').check();
  await page.locator('[name=art]').selectOption({label:'Nghiên cứu nét'});
  await page.locator('[name=score]').fill('8');
  await page.locator('#complete button').click();
  await waitText('#complete button','Cập nhật đánh giá');
  await page.locator('#complete button').click();
  await page.waitForTimeout(100);
  const events=await page.evaluate(async()=>{const {openDatabase,read}=await import('./js/database.js');await openDatabase();return (await read('state')).events;});
  assert.equal(Object.values(events).reduce((a,b)=>a+b,0),100);
  await open('skills','Cây kỹ năng');
  await waitText('#skill-tree a','Nét thẳng tự tin · Hoàn thành');
  await open('import','Nhập chương trình');
  const template=await readFile(new URL('../data/lesson-template.json',import.meta.url));
  await page.locator('#import-file').setInputFiles({name:'template.json',mimeType:'application/json',buffer:template});
  await waitText('#import-preview','Thêm mới');
  await page.locator('#do-import').click();
  await waitText('main h1','Lộ trình học');
  assert.equal(await page.locator('.route-card').count(),34);
  await open('import','Nhập chương trình');
  const payload=JSON.parse(template);
  Object.assign(payload.lessons[0],{id:'zip-lesson',title:'Bài học ZIP',illustrations:['images/icon.png'],coreTheoryMarkdown:'notes/core.md'});
  const icon=await readFile(new URL('../assets/icons/academy-192.png',import.meta.url));
  const bundle=await pack([['curriculum.json',JSON.stringify(payload)],['images/icon.png',icon],['notes/core.md','Ghi chú <b>giữ dưới dạng văn bản</b>.']]);
  await page.locator('#import-file').setInputFiles({name:'curriculum.zip',mimeType:'application/zip',buffer:Buffer.from(await bundle.arrayBuffer())});
  await waitText('#import-preview','Bài học ZIP');
  await page.locator('#do-import').click();
  await waitText('main h1','Lộ trình học');
  await open('lesson/zip-lesson','Bài học ZIP');
  await waitText('.lesson p','<b>giữ dưới dạng văn bản</b>');
  assert.equal(await page.locator('.lesson img').evaluate(img=>img.decode().then(()=>img.naturalWidth)),192);
  await open('profile','Hồ sơ họa sĩ');
  await page.locator('#theme-profile').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  const downloaded=page.waitForEvent('download');
  await page.locator('#backup').click();
  const backup=await downloaded;
  assert.equal(backup.suggestedFilename(),'dz-backup.zip');
  const blob=await readFile(await backup.path());
  const reload=page.waitForEvent('load');
  await page.locator('#restore').setInputFiles({name:'dz-backup.zip',mimeType:'application/zip',buffer:blob});
  await reload;
  await open('portfolio','Portfolio');
  await waitText('.gallery h3','Nghiên cứu nét');
  await open('lesson/zip-lesson','Bài học ZIP');
  assert.equal(await page.locator('.lesson img').evaluate(img=>img.decode().then(()=>img.naturalWidth)),192);
  for(const [route,title] of [['perspective','Phòng phối cảnh'],['color','Xưởng màu'],['sprite','Sprite Animation'],['projects','Dự án nghệ thuật'],['anatomy','Phòng giải phẫu'],['characters','Thiết kế nhân vật'],['analytics','Thống kê luyện vẽ'],['review','Sổ ôn tập'],['training','Lịch luyện tập'],['references','Kho tham chiếu']])await open(route,title);
  await context.setOffline(true);
  await page.reload();
  await waitText('main h1','Kho tham chiếu');
  await open('practice/line','Bàn vẽ');
  await waitText('#draft-status','đã lưu');
  assert.deepEqual(errors,[]);
  const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  const touchPage=await mobile.newPage();
  await touchPage.goto(url+'#practice');
  const touchCanvas=touchPage.locator('canvas');
  await touchCanvas.scrollIntoViewIfNeeded();
  await touchPage.waitForFunction(()=>document.querySelector('canvas').width>300);
  const box=await touchCanvas.boundingBox();
  const beforeTouch=await touchCanvas.evaluate(c=>c.toDataURL());
  const cdp=await mobile.newCDPSession(touchPage);
  const x=box.x+box.width/2,y=box.y+box.height/2;
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x,y}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:x+45,y:y+32}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.equal((await touchCanvas.evaluate(c=>c.toDataURL()))!==beforeTouch,true,'Touch should change canvas pixels.');
  assert.equal(await touchPage.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await touchPage.locator('#mobile').isVisible(),true);
  console.log('PASS desktop, drawing, draft, timer, progression, curriculum, backup, offline and mobile touch');
}finally{await browser.close();}

